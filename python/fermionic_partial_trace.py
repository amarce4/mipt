def _ordinary_suffix_trace_density_matrix(
    rho: np.ndarray,
    keep_dim: int,
    trace_dim: int,
    basis_order: BasisOrder,
) -> np.ndarray:
    out = np.zeros((keep_dim, keep_dim), dtype=np.complex128)
    for tr in range(trace_dim):
        idx = _suffix_block_indices(keep_dim, trace_dim, tr, basis_order)
        out += rho[np.ix_(idx, idx)]
    return out


def _run_self_tests() -> None:
    rng = np.random.default_rng(12345)

    # Statevector path equals density-matrix path for pure states.
    for basis_order in ("little", "big"):
        n = 4
        dim = 1 << n
        psi = rng.normal(size=dim) + 1j * rng.normal(size=dim)
        psi = psi.astype(np.complex128)
        psi /= np.linalg.norm(psi)
        rho = np.outer(psi, psi.conjugate())
        for keep in ([0, 2], [2, 0], [3, 0, 1], [1]):
            a = fermionic_partial_trace_statevector(psi, keep=keep, basis_order=basis_order)
            b = fermionic_partial_trace_density_matrix(rho, keep=keep, basis_order=basis_order)
            if not np.allclose(a, b, atol=1e-12):
                raise AssertionError((basis_order, keep, np.max(np.abs(a - b))))
            if not np.allclose(np.trace(a), 1.0, atol=1e-12):
                raise AssertionError((basis_order, keep, np.trace(a)))
            if not np.allclose(a, a.conjugate().T, atol=1e-12):
                raise AssertionError((basis_order, keep, "non-Hermitian"))

    # Keeping a canonical prefix requires no fermionic reordering; it is the
    # ordinary suffix trace.
    for basis_order in ("little", "big"):
        n = 4
        dim = 1 << n
        x = rng.normal(size=(dim, dim)) + 1j * rng.normal(size=(dim, dim))
        rho = x @ x.conjugate().T
        rho /= np.trace(rho)
        keep = [0, 1]
        got = fermionic_partial_trace_density_matrix(rho, keep=keep, basis_order=basis_order)
        want = _ordinary_suffix_trace_density_matrix(
            rho, keep_dim=4, trace_dim=4, basis_order=basis_order
        )
        if not np.allclose(got, want, atol=1e-12):
            raise AssertionError((basis_order, "prefix trace mismatch", np.max(np.abs(got - want))))

    # TMI of a product pure state should be zero.
    psi0 = np.zeros(8, dtype=np.complex128)
    psi0[0] = 1.0
    if abs(fermionic_tmi_from_statevector(psi0, modes=[0, 1, 2], n_modes=3)) > 1e-12:
        raise AssertionError("product-state TMI should be zero")

    print("fermionic_partial_trace.py self-tests passed")


if __name__ == "__main__":
    _run_self_tests()

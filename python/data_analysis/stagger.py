"""Two-probe mode 5: propagation velocities from staggered probe insertions.

``mipt_probed.exe 2 N reals circ 5 p s_max r_max delta_max`` Bell-entangles
ancilla ``A`` with a random site ``x0`` after equilibration, waits ``Delta``
timesteps, Bell-entangles ancilla ``B`` with ``x0 + r``, and then records
``rho_AB`` for every elapsed ``s``. Both ancillas sit outside the circuit, so a
system-only unitary acts as the identity on ``rho_AB`` and cannot correlate them
at all: every ``A``--``B`` correlation seen here is generated by the intervening
measurement record.

Why this and not the one-probe front
------------------------------------
The one-probe protocol (:mod:`data_analysis.front`) watches a single injected
ebit spread into receiver blocks of fixed width. Its classical channel is easy to
follow, but its negativity vanishes *exactly* a few sites out -- the reference's
one ebit delocalizes and a microscopic receiver's marginal becomes PPT -- so the
entanglement front has a range rather than a velocity. Two isolated qubit
ancillas do not have that problem: ``rho_AB`` is 2x2 by 2x2, where ``N = 0``
unambiguously means separable, and the correlation being measured is created
rather than diluted.

The price is that ``s_arr`` here confounds two propagation legs, so a naive
velocity would carry a factor-of-two ambiguity. The staggered insertion removes
it. If the two influence regions travel at ``v_mu`` and meet, the arrival time
after the second insertion behaves as

    s_arr(r, Delta) = b + c * max(lambda_mu * r - Delta, 0),

with ``c = 1/2`` for a meet-in-the-middle mechanism and ``c = 1`` for a one-way
crossing -- but *either way* the kink sits at

    Delta_c(r) = b' + lambda_mu * r,

so the slope of the breakpoint against separation is the one-way ``lambda_mu``
regardless of which mechanism is at work. That is what this module fits, and it
is the reason the delay axis is scanned at all.

The last panel then reports ``Delta_{N,c}(r) - Delta_{J,c}(r)``, which separates
the three hypotheses directly: growing linearly means genuinely different
velocities, constant means one velocity plus a fixed entanglement-formation
delay, and sublinear growth means the gap is a detectability effect of the
threshold rather than a front.

Two things to know before reading a number off this
---------------------------------------------------
``J`` is the Henderson--Vedral classical correlation, maximized over every
projective measurement of ``A``, and ``D = I - J`` is the quantum discord --
*not* entanglement. A discord front says quantum correlation arrived, which is a
weaker claim than the negativity front makes.

Arrival times oscillate with the parity of ``Delta``. One timestep is one
brickwork layer, so consecutive delays insert ``B`` into layers of opposite bond
parity and the first layer acting on ``B``'s partner site couples it in
different directions. The oscillation is real, not noise, and it enters
``Delta_c`` as extra scatter rather than as a bias so long as the fit window
holds both parities. ``delta_parity`` fits one parity at a time when that needs
checking.
"""

